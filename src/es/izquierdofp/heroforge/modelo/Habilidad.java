package es.izquierdofp.heroforge.modelo;

/**
 *
 * @author 2DAM
 */
public class Habilidad {
    private int id;
    private int personaje_id;
    private String nombre;
    private int nivel;
    private String descripcion;

    public Habilidad(int id, int personaje_id, String nombre, int nivel, String descripcion) {
        this.id = id;
        this.personaje_id = personaje_id;
        this.nombre = nombre;
        this.nivel = nivel;
        this.descripcion = descripcion;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public int getPersonaje_id() {
        return personaje_id;
    }

    public void setPersonaje_id(int personaje_id) {
        this.personaje_id = personaje_id;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public int getNivel() {
        return nivel;
    }

    public void setNivel(int nivel) {
        this.nivel = nivel;
    }

    public String getDescripcion() {
        return descripcion;
    }

    public void setDescripcion(String descripcion) {
        this.descripcion = descripcion;
    }
    
    
}
